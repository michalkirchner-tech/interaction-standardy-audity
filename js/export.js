// Export přehledu výsledků do PDF (tisk prohlížeče) a do Excelu (.xlsx bez externích knihoven)

const escH = s => String(s ?? "").replace(/[&<>"']/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));

// ---------- PDF ----------
// table = { title, subtitle, head: [..], rows: [[..]], rowClass?: [..] }
export function exportPdf(table) {
  let box = document.getElementById("printExport");
  if (!box) { box = document.createElement("div"); box.id = "printExport"; document.body.appendChild(box); }
  box.innerHTML = `
    <div class="px-head"><img src="assets/interaction-logo.png" alt=""><div><h1>${escH(table.title)}</h1><p>${escH(table.subtitle || "")}</p></div></div>
    <table class="px-table"><thead><tr>${table.head.map(h => `<th>${escH(h)}</th>`).join("")}</tr></thead>
    <tbody>${table.rows.map((r, i) => `<tr class="${table.rowClass?.[i] || ""}">${r.map(c => `<td>${escH(c).replace(/\n/g, "<br>")}</td>`).join("")}</tr>`).join("")}</tbody></table>`;
  const page = document.createElement("style");
  page.textContent = "@page{size:A4 landscape;margin:10mm}";
  document.head.appendChild(page);
  document.body.classList.add("printing-export");
  const prevTitle = document.title;
  document.title = table.title;
  let done = false;
  const cleanup = () => { if (done) return; done = true; document.body.classList.remove("printing-export"); page.remove(); document.title = prevTitle; window.removeEventListener("afterprint", cleanup); };
  window.addEventListener("afterprint", cleanup);
  setTimeout(() => window.print(), 60);
  setTimeout(cleanup, 20000);
}

